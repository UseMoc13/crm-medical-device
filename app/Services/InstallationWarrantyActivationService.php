<?php

namespace App\Services;

use App\Models\Delivery;
use App\Models\DeliveryItem;
use App\Models\Installation;
use App\Models\SerialNumber;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Str;
use Illuminate\Validation\ValidationException;

class InstallationWarrantyActivationService
{
    /** @return array{created:int, existing:int} */
    public function activate(Installation $installation): array
    {
        return DB::transaction(function () use ($installation): array {
            $record = Installation::query()->whereKey($installation->getKey())->lockForUpdate()->firstOrFail();

            if ($record->status !== 'Completed') {
                throw ValidationException::withMessages(['installation' => 'Complete the Installation before activating warranties.']);
            }

            $delivery = Delivery::query()->with('salesOrder.quotation.opportunity')
                ->whereKey($record->delivery_id)->lockForUpdate()->firstOrFail();
            if (strtolower((string) $delivery->status) !== 'delivered') {
                throw ValidationException::withMessages(['delivery' => 'The linked Delivery must be Delivered.']);
            }

            $customerId = $delivery->salesOrder?->quotation?->opportunity?->customer_id;
            if (!$customerId) {
                throw ValidationException::withMessages([
                    'customer' => 'The Sales Order has no customer linked through its Quotation and Opportunity.',
                ]);
            }

            $items = DeliveryItem::query()->where('delivery_id', $delivery->getKey())
                ->orderBy('serial_number_id')->get();
            if ($items->isEmpty()) {
                throw ValidationException::withMessages(['serial_number' => 'No delivered serial numbers were found.']);
            }

            $ids = $items->pluck('serial_number_id');
            if ($ids->contains(null) || $ids->unique()->count() !== $items->count()) {
                throw ValidationException::withMessages([
                    'serial_number' => 'Delivered device serial numbers must be complete and unique.',
                ]);
            }

            $serials = SerialNumber::query()->with('product')->whereIn('serial_number_id', $ids)
                ->orderBy('serial_number_id')->lockForUpdate()->get();
            if ($serials->count() !== $items->count()) {
                throw ValidationException::withMessages(['serial_number' => 'Some delivered serial numbers no longer exist.']);
            }

            foreach ($serials as $serial) {
                if (strtolower((string) $serial->status) !== 'installed') {
                    throw ValidationException::withMessages([
                        'serial_number' => "Device {$serial->serial_number} is not Installed.",
                    ]);
                }
                if ($serial->customer_id && $serial->customer_id !== $customerId) {
                    throw ValidationException::withMessages([
                        'customer' => "Device {$serial->serial_number} belongs to a different customer.",
                    ]);
                }
                // Product warranty_period is interpreted as months; confirm with product master data.
                if (!$serial->product || (int) $serial->product->warranty_period <= 0) {
                    throw ValidationException::withMessages([
                        'warranty_period' => "Product warranty period is missing or invalid for {$serial->serial_number}.",
                    ]);
                }
            }

            $existing = DB::table('warranties')->whereIn('serial_number_id', $ids)
                ->orderBy('serial_number_id')->lockForUpdate()->get()->groupBy('serial_number_id');
            foreach ($serials as $serial) {
                foreach ($existing->get($serial->getKey(), collect()) as $warranty) {
                    if ($warranty->customer_id !== $customerId) {
                        throw ValidationException::withMessages([
                            'customer' => "Existing warranty for {$serial->serial_number} belongs to a different customer.",
                        ]);
                    }
                }
            }

            // PostgreSQL transactional lock serializes numbers generated by this integration.
            $year = now()->format('Y');
            DB::select('SELECT pg_advisory_xact_lock(hashtext(?))', ["crm-warranty-number-{$year}"]);
            $prefix = "WTY-{$year}-";
            $next = DB::table('warranties')->where('warranty_number', 'like', $prefix . '%')
                ->pluck('warranty_number')->reduce(function (int $max, string $number) use ($prefix): int {
                    $suffix = substr($number, strlen($prefix));
                    return ctype_digit($suffix) ? max($max, (int) $suffix) : $max;
                }, 0) + 1;

            $start = today();
            $created = 0;
            $skipped = 0;
            foreach ($serials as $serial) {
                // Existing coverage must never be silently extended or reset.
                if ($existing->has($serial->getKey())) {
                    $skipped++;
                    continue;
                }
                if (!$serial->customer_id) {
                    $serial->customer_id = $customerId;
                    $serial->save();
                }

                DB::table('warranties')->insert([
                    'warranty_id' => (string) Str::uuid(),
                    'serial_number_id' => $serial->getKey(),
                    'customer_id' => $customerId,
                    'warranty_number' => $prefix . str_pad((string) $next++, 4, '0', STR_PAD_LEFT),
                    'start_date' => $start->toDateString(),
                    'end_date' => $start->copy()->addMonthsNoOverflow((int) $serial->product->warranty_period)->toDateString(),
                    'warranty_type' => 'Manufacturer',
                    'status' => 'Active',
                    'terms' => 'Standard manufacturer warranty activated from completed Installation.',
                    'created_at' => now(),
                    'updated_at' => now(),
                ]);
                $created++;
            }
            return ['created' => $created, 'existing' => $skipped];
        }, 3);
    }
}
